### FLOATS
# divided integers still end up as floats, even when the result is a whole number.

print(8 / 2)

# result would be 4.0

# python treats operations with floats in it, automatically resulting in a float even if it's a whole number.
# = integer plus float will still give you a float

print(2 + 2.0)

# will give you 4.0

print(4 * 2.0)

# will give you 8.0

print(4.0**2)
# will give you 16.0

